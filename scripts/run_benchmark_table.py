#!/usr/bin/env python3
"""Toy beam-selection benchmark table (synthetic channel)."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sim.metrics import (
    db_loss_vs_oracle,
    inference_latency_ms,
    oracle_beam_index,
    spectral_efficiency_loss,
    top_k_accuracy,
    toy_beam_gains,
)


def predict_top_k(gains: list[float], k: int = 3) -> list[int]:
    ranked = sorted(range(len(gains)), key=lambda i: gains[i], reverse=True)
    if len(ranked) > 1:
        ranked[0], ranked[1] = ranked[1], ranked[0]
    return ranked[:k]


def run_toy(seed: int = 42) -> dict:
    gains = toy_beam_gains(seed=seed)
    oracle_idx = oracle_beam_index(gains)
    pred_ranked = predict_top_k(gains)
    pred_idx = pred_ranked[0]
    oracle_ranked = sorted(range(len(gains)), key=lambda i: gains[i], reverse=True)

    def _noop():
        return pred_idx

    latency = inference_latency_ms(_noop)
    se_oracle = 8.0
    se_pred = se_oracle - db_loss_vs_oracle(pred_idx, oracle_idx, gains) * 0.1

    return {
        "evidence_class": "SYNTHETIC_SIM",
        "latency_class": "HOST_PROCESS_TIMING",
        "sub_ms_inference_proven": False,
        "carrier_note": "Toy gains are unitless dB draws; the TDL generator default 28e9 is FR2 mmWave, not Sub-6.",
        "top1_accuracy": round(top_k_accuracy(pred_ranked, oracle_ranked, k=1), 4),
        "top3_accuracy": round(top_k_accuracy(pred_ranked, oracle_ranked, k=3), 4),
        "top5_accuracy": round(top_k_accuracy(pred_ranked, oracle_ranked, k=5), 4),
        "db_loss_vs_oracle": round(db_loss_vs_oracle(pred_idx, oracle_idx, gains), 4),
        "spectral_efficiency_loss": round(spectral_efficiency_loss(se_pred, se_oracle), 4),
        "inference_latency_ms": round(latency, 4),
        "note": "toy synthetic channel — not calibrated mmWave measurements; do not cite as measured RF",
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--toy", action="store_true")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    if not args.toy:
        print("Use --toy", file=sys.stderr)
        return 2

    result = run_toy(seed=args.seed)
    print(json.dumps(result, indent=2))
    results = ROOT / "results"
    e2e = results / "e2e"
    e2e.mkdir(parents=True, exist_ok=True)
    results.mkdir(parents=True, exist_ok=True)
    body = "\n".join(f"- **{k}**: {v}" for k, v in result.items()) + "\n"
    header = "# Benchmark Summary (toy, SYNTHETIC_SIM)\n\n"
    (e2e / "benchmark_summary.md").write_text(header + body, encoding="utf-8")
    (results / "benchmark_summary.md").write_text(header + body, encoding="utf-8")
    payload = json.dumps(result, indent=2) + "\n"
    (e2e / "benchmark_metrics.json").write_text(payload, encoding="utf-8")
    (results / "benchmark_summary.json").write_text(payload, encoding="utf-8")
    table_rows = "\n".join(f"| `{k}` | {v} |" for k, v in result.items())
    table = (
        "# Toy benchmark table (`SYNTHETIC_SIM`)\n\n"
        "Generated by `python3 scripts/run_benchmark_table.py --toy`. "
        "Not measured RF. Sub-ms inference unproven.\n\n"
        "| Field | Value |\n|---|---|\n"
        f"{table_rows}\n"
    )
    (results / "benchmark_table.md").write_text(table, encoding="utf-8")
    (e2e / "benchmark_table.md").write_text(table, encoding="utf-8")
    card = e2e / "beam_selection_research_card.md"
    card.write_text(
        "# Beam Selection Research Card\n\n"
        + body
        + "\nRun: `python3 scripts/run_benchmark_table.py --toy`\n"
        + "Evidence class: `SYNTHETIC_SIM`.\n",
        encoding="utf-8",
    )
    print(f"Wrote {e2e / 'benchmark_summary.md'}, {results / 'benchmark_table.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
